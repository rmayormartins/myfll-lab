// dígitos 3x5 para o número do programa na tela ociosa
export const DIGITS3 = {
  0: '111:101:101:101:111', 1: '010:110:010:010:111', 2: '111:001:111:100:111', 3: '111:001:111:001:111',
  4: '101:101:111:001:001', 5: '111:100:111:001:111', 6: '111:100:111:101:111', 7: '111:001:010:010:010',
  8: '111:101:111:101:111', 9: '111:101:111:001:111',
};
export function slotPixels(n) {
  const px = new Array(25).fill(0);
  const put = (d, x0) => { const rows = DIGITS3[d].split(':'); for (let y = 0; y < 5; y++) for (let x = 0; x < 3; x++) if (rows[y][x] === '1') px[y * 5 + x0 + x] = 100; };
  n = Math.max(0, Math.min(19, n | 0));
  if (n < 10) put(n, 1);
  else { for (let y = 0; y < 5; y++) px[y * 5] = 100; put(n - 10, 2); }
  return px;
}
